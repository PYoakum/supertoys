/**
 * @fileoverview Report Generator for evaluation output artifacts
 * @module report-generator
 */

import { mkdir, writeFile } from 'fs/promises';
import { join } from 'path';
import { existsSync } from 'fs';

/**
 * Report Generator class
 */
export class ReportGenerator {
  /**
   * @param {string} outputDir - Output directory
   */
  constructor(outputDir) {
    this.outputDir = outputDir;
  }

  /**
   * Generate all reports
   * @param {string} sessionId
   * @param {Object} evaluationResult
   * @param {Object} metadata
   * @returns {Promise<Object>}
   */
  async generateAll(sessionId, evaluationResult, metadata) {
    const sessionDir = join(this.outputDir, sessionId);
    
    // Ensure directories exist
    await mkdir(join(sessionDir, 'recommendations'), { recursive: true });

    const files = {};

    // Generate main report (Markdown)
    files.reportMd = await this.generateMarkdownReport(sessionDir, sessionId, evaluationResult, metadata);

    // Generate JSON report
    files.reportJson = await this.generateJsonReport(sessionDir, sessionId, evaluationResult, metadata);

    // Generate learnings document
    files.learnings = await this.generateLearningsDoc(sessionDir, evaluationResult);

    // Generate recommendation documents
    files.toolRouterRecs = await this.generateToolRouterRecs(sessionDir, evaluationResult);
    files.requirementsRecs = await this.generateRequirementsRecs(sessionDir, evaluationResult);
    files.languageRecs = await this.generateLanguageRecs(sessionDir, evaluationResult);

    // Generate metadata
    files.metadata = await this.generateMetadata(sessionDir, sessionId, evaluationResult, metadata);

    return files;
  }

  /**
   * Generate Markdown report
   * @private
   */
  async generateMarkdownReport(sessionDir, sessionId, result, metadata) {
    const { qualityScore } = result;
    const filepath = join(sessionDir, 'evaluation-report.md');

    const breakdownRows = Object.entries(qualityScore.breakdown || {})
      .map(([dim, data]) => {
        const name = dim.replace(/([A-Z])/g, ' $1').trim();
        return `| ${name} | ${data.score} | ${Math.round(data.weight * 100)}% | ${data.weighted?.toFixed(1) || 'N/A'} |`;
      })
      .join('\n');

    const content = `# Session Evaluation Report

**Session ID:** ${sessionId}  
**Evaluated At:** ${metadata.evaluatedAt}  
**Evaluator Version:** ${metadata.version}

---

## Executive Summary

**Overall Score:** ${qualityScore.overall}/100 (${qualityScore.grade})

${qualityScore.summary}

### Score Breakdown

| Dimension | Score | Weight | Weighted |
|-----------|-------|--------|----------|
${breakdownRows}
| **Overall** | | | **${qualityScore.overall}** |

---

## Detailed Scoring

${this.formatDetailedScoring(qualityScore.breakdown)}

---

## Tool Router Recommendations

${this.formatToolRecommendations(result.toolRouterRecommendations)}

---

## Requirements Analysis

${this.formatRequirementsAnalysis(result.requirementsAnalysis)}

---

## Language & Encoding Recommendations

${this.formatLanguageRecommendations(result.languageRecommendations)}

---

## Key Learnings

${this.formatLearnings(result.learningsSummary)}

---

## Action Items

${this.formatActionItems(result.learningsSummary?.actionItems)}

---

*Generated by Output Evaluation Service v${metadata.version}*
`;

    await writeFile(filepath, content, 'utf-8');
    return filepath;
  }

  /**
   * Format detailed scoring section
   * @private
   */
  formatDetailedScoring(breakdown) {
    if (!breakdown) return 'No breakdown available.';

    return Object.entries(breakdown).map(([dim, data]) => {
      const name = dim.replace(/([A-Z])/g, ' $1').trim();
      const strengths = (data.strengths || []).map(s => `- ${s}`).join('\n') || '- None identified';
      const weaknesses = (data.weaknesses || []).map(w => `- ${w}`).join('\n') || '- None identified';

      return `### ${name} (${data.score}/100)

**Rationale:** ${data.rationale || 'N/A'}

**Strengths:**
${strengths}

**Areas for Improvement:**
${weaknesses}
`;
    }).join('\n');
  }

  /**
   * Format tool recommendations
   * @private
   */
  formatToolRecommendations(recs) {
    if (!recs) return 'No recommendations.';

    let content = '';

    if (recs.featureRequests?.length > 0) {
      content += '### Feature Requests\n\n';
      recs.featureRequests.forEach((fr, i) => {
        content += `#### FR-${String(i + 1).padStart(3, '0')}: ${fr.title || 'Untitled'}\n\n`;
        content += `- **Tool:** ${fr.toolName || 'N/A'}\n`;
        content += `- **Priority:** ${fr.priority || 'medium'}\n\n`;
        content += `${fr.description || ''}\n\n`;
      });
    }

    if (recs.newTools?.length > 0) {
      content += '### New Tool Suggestions\n\n';
      recs.newTools.forEach((nt, i) => {
        content += `#### NT-${String(i + 1).padStart(3, '0')}: ${nt.proposedName || 'Untitled'}\n\n`;
        content += `${nt.description || ''}\n\n`;
      });
    }

    if (recs.usageAnalysis?.observations) {
      content += `### Usage Analysis\n\n${recs.usageAnalysis.observations}\n\n`;
    }

    return content || 'No recommendations.';
  }

  /**
   * Format requirements analysis
   * @private
   */
  formatRequirementsAnalysis(analysis) {
    if (!analysis) return 'No analysis available.';

    let content = '';

    if (analysis.unclearRequirements?.length > 0) {
      content += '### Unclear Requirements\n\n';
      analysis.unclearRequirements.forEach((ur, i) => {
        content += `#### UR-${String(i + 1).padStart(3, '0')}\n\n`;
        content += `**Original:** ${ur.originalText || 'N/A'}\n\n`;
        content += `**Issue:** ${ur.issue || 'N/A'}\n\n`;
        content += `**Suggested Revision:** ${ur.suggestedRevision || 'N/A'}\n\n`;
      });
    }

    if (analysis.missingRequirements?.length > 0) {
      content += '### Missing Requirements\n\n';
      analysis.missingRequirements.forEach((mr, i) => {
        content += `- **MR-${String(i + 1).padStart(3, '0')}:** ${mr.description || mr}\n`;
      });
      content += '\n';
    }

    return content || 'No issues identified.';
  }

  /**
   * Format language recommendations
   * @private
   */
  formatLanguageRecommendations(recs) {
    if (!recs) return 'No recommendations.';

    let content = '';

    if (recs.promptImprovements?.length > 0) {
      content += '### Prompt Improvements\n\n';
      recs.promptImprovements.forEach((pi, i) => {
        content += `${i + 1}. ${pi.issue || pi}\n`;
      });
      content += '\n';
    }

    if (recs.encoding?.length > 0) {
      content += '### Encoding Recommendations\n\n';
      recs.encoding.forEach((er, i) => {
        content += `${i + 1}. ${er.recommendation || er}\n`;
      });
      content += '\n';
    }

    return content || 'No recommendations.';
  }

  /**
   * Format learnings
   * @private
   */
  formatLearnings(learnings) {
    if (!learnings) return 'No learnings captured.';

    let content = '';

    if (learnings.keyLearnings?.length > 0) {
      learnings.keyLearnings.forEach((kl, i) => {
        content += `### ${i + 1}. ${kl.title || 'Learning'}\n\n`;
        content += `${kl.description || kl}\n\n`;
      });
    }

    if (learnings.successPatterns?.length > 0) {
      content += '### Success Patterns\n\n';
      learnings.successPatterns.forEach(sp => {
        content += `- ${sp.pattern || sp}\n`;
      });
      content += '\n';
    }

    if (learnings.failurePatterns?.length > 0) {
      content += '### Failure Patterns\n\n';
      learnings.failurePatterns.forEach(fp => {
        content += `- ${fp.pattern || fp}\n`;
      });
      content += '\n';
    }

    return content || 'No learnings captured.';
  }

  /**
   * Format action items
   * @private
   */
  formatActionItems(items) {
    if (!items || items.length === 0) return 'No action items.';

    return items.map((item, i) => {
      return `| ${item.priority || 'medium'} | ${item.action || item} | ${item.owner || 'TBD'} |`;
    }).join('\n');
  }

  /**
   * Generate JSON report
   * @private
   */
  async generateJsonReport(sessionDir, sessionId, result, metadata) {
    const filepath = join(sessionDir, 'evaluation-report.json');

    const report = {
      metadata: {
        reportId: `eval-${sessionId}-${Date.now()}`,
        sessionId,
        evaluatedAt: metadata.evaluatedAt,
        evaluatorVersion: metadata.version,
        modelUsed: metadata.modelUsed,
        tokenUsage: metadata.tokenUsage,
        evaluationDurationMs: metadata.durationMs
      },
      ...result
    };

    await writeFile(filepath, JSON.stringify(report, null, 2), 'utf-8');
    return filepath;
  }

  /**
   * Generate learnings document
   * @private
   */
  async generateLearningsDoc(sessionDir, result) {
    const filepath = join(sessionDir, 'learnings.md');
    const { learningsSummary } = result;

    const content = `# Session Learnings

---

## Top Key Learnings

${(learningsSummary?.keyLearnings || []).map((kl, i) => `
### ${i + 1}. ${kl.title || 'Learning'}

${kl.description || kl}

${kl.evidence ? `**Evidence:** ${kl.evidence}` : ''}
`).join('\n') || 'No key learnings captured.'}

---

## Success Patterns

${(learningsSummary?.successPatterns || []).map(sp => `
### Pattern: ${sp.pattern || sp}

${sp.instances ? `**Observed In:** ${sp.instances.join(', ')}` : ''}

${sp.recommendation ? `**Recommendation:** ${sp.recommendation}` : ''}
`).join('\n') || 'No success patterns identified.'}

---

## Failure Patterns

${(learningsSummary?.failurePatterns || []).map(fp => `
### Pattern: ${fp.pattern || fp}

${fp.rootCause ? `**Root Cause:** ${fp.rootCause}` : ''}

${fp.prevention ? `**Prevention:** ${fp.prevention}` : ''}
`).join('\n') || 'No failure patterns identified.'}

---

## Prioritized Actions

${(learningsSummary?.actionItems || []).map((item, i) => `
${i + 1}. **${item.action || item}**
   - Priority: ${item.priority || 'medium'}
   - Owner: ${item.owner || 'TBD'}
`).join('\n') || 'No action items.'}

---

*Apply these learnings to improve future sessions.*
`;

    await writeFile(filepath, content, 'utf-8');
    return filepath;
  }

  /**
   * Generate tool router recommendations doc
   * @private
   */
  async generateToolRouterRecs(sessionDir, result) {
    const filepath = join(sessionDir, 'recommendations', 'tool-router.md');
    const recs = result.toolRouterRecommendations || {};

    const content = `# Tool Router Recommendations

${this.formatToolRecommendations(recs)}

---

*Generated by Output Evaluation Service*
`;

    await writeFile(filepath, content, 'utf-8');
    return filepath;
  }

  /**
   * Generate requirements recommendations doc
   * @private
   */
  async generateRequirementsRecs(sessionDir, result) {
    const filepath = join(sessionDir, 'recommendations', 'requirements.md');
    const analysis = result.requirementsAnalysis || {};

    const content = `# Requirements Analysis

${this.formatRequirementsAnalysis(analysis)}

---

*Generated by Output Evaluation Service*
`;

    await writeFile(filepath, content, 'utf-8');
    return filepath;
  }

  /**
   * Generate language recommendations doc
   * @private
   */
  async generateLanguageRecs(sessionDir, result) {
    const filepath = join(sessionDir, 'recommendations', 'language.md');
    const recs = result.languageRecommendations || {};

    const content = `# Language & Encoding Recommendations

${this.formatLanguageRecommendations(recs)}

---

*Generated by Output Evaluation Service*
`;

    await writeFile(filepath, content, 'utf-8');
    return filepath;
  }

  /**
   * Generate metadata file
   * @private
   */
  async generateMetadata(sessionDir, sessionId, result, metadata) {
    const filepath = join(sessionDir, 'metadata.json');

    const data = {
      sessionId,
      evaluatedAt: metadata.evaluatedAt,
      evaluatorVersion: metadata.version,
      modelUsed: metadata.modelUsed,
      tokenUsage: metadata.tokenUsage,
      evaluationDurationMs: metadata.durationMs,
      overallScore: result.qualityScore?.overall,
      grade: result.qualityScore?.grade
    };

    await writeFile(filepath, JSON.stringify(data, null, 2), 'utf-8');
    return filepath;
  }
}

export default ReportGenerator;
